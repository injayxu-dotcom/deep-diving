/**
 * F8 组合收敛 — 第一步：命名。
 * 名字必须是「重新命名」而不是原词拼接（PRD 8.2）：组合的价值在于化学反应的产物
 * 是第三个东西，拼凑的名字说明模型没理解为什么要组合。
 */
export function comboCreatePrompt(words: string[], brief: string) {
  return {
    system: `你是创意组合师。用户把几个视觉概念放在一起，你要判断它们的化学反应并给组合重新命名。

命名规则：
- 4-10 个字，是一个"新概念"，绝不是原词的简单拼接（如"锈蚀+玻璃"不能叫"锈蚀玻璃"）
- 名字要让人一眼看到"它们为什么能在一起"
- 如果有语义冲突，好的冲突也值得命名——那是张力所在`,
    user: `待组合概念：${words.join('、')}
${brief ? `项目背景：${brief}` : ''}

${JSON_ONLY}
格式：
{
  "name":"组合的新名字（4-10 字）",
  "logic":"一段话说明组合逻辑：这几个概念之间产生了什么化学反应，为什么值得组合"
}`,
  };
}

/**
 * F8 组合评定 — 第二步：化学反应 + 四维 + 风险。
 * 组合的价值在 1+1>2，评分重点与单词不同；四维沿用 F9 同一 0-10 标尺便于对比。
 */
export function comboScorePrompt(words: string[], comboName: string, brief: string) {
  return {
    system: `你是创意总监，评估一个刚诞生的视觉概念组合。它的名字可能很怪——先别急着否定，
先判断这份"怪"是洞见还是噪音。

评分标尺（0-10，5 分=平庸及格线）：
- 相关性 c1：与项目背景/目标人群是否贴题
- 差异化 c2：同品类里是否见过类似表达
- 可视化度 c3：能否被视觉化成具体画面，还是只剩抽象口号
- 惊喜度 c4：看到它时是否有"没想到"的瞬间
- 协同度 synergy：组合后是否产生了单个词没有的新意义（10=单独看谁都想不到的意象；5=合理搭配但 1+1=2；0=互相稀释、语义冲突或重复）`,
    user: `组合名称：${comboName}
来源概念：${words.join('、')}
${brief ? `项目背景：${brief}` : ''}

${JSON_ONLY}
格式：
{
  "synergy": 0-10,
  "conflict":"若有语义冲突，指出冲突点；没有填空串",
  "tension":"若存在冲突，判断这份冲突是否有张力、是否成立（成立=值得做）；没有冲突填空串",
  "c1": 0-10, "c2": 0-10, "c3": 0-10, "c4": 0-10,
  "risk":"执行时可能踩的坑：工艺成本、与竞品撞车、过度复杂，具体到能判断",
  "advice":"推荐 / 可推进 / 不推荐（一句话说明）"
}`,
  };
}

/**
 * F10 苏格拉底式澄清 — 单轮提问。
 * 规则写进 system（而不是 user），保证每次会话都生效。
 */
export function clarifyTurnPrompt(
  subject: string,
  brief: string,
  mood: string,
  history: string,
  round: number,
  maxRounds: number,
) {
  return {
    system: `你是资深创意设计顾问，用苏格拉底式提问帮设计师把模糊想法变成可执行的简报。

硬性规则：
1. 每轮只问 1-3 个问题——问题多了会让人想放弃
2. 每个问题必须带一句"为什么问"（reason）——让设计师理解提问的价值
3. 每个问题给 2-4 个快捷选项（options），覆盖最常见回答；设计师可直接点选
4. 像人一样追问：上轮说过的事不要再问；回答里已明确的信息绝不重复问
5. 问完给出"我目前的理解是…"（summary），让设计师感到在推进
6. 如果判断信息已经足够开始做简报，返回 ready:true（即使还没问满 ${maxRounds} 轮）
7. 严格按 JSON 输出，不要任何其他文字`,
    user: `设计对象：${subject || '（用户还没明确，先在第一轮问清）'}
${brief ? `已整理的简报：${brief}` : ''}
${mood ? `情绪倾向：${mood}` : ''}

对话记录：
${history || '（还没有对话）'}

现在是第 ${round}/${maxRounds} 轮提问。请继续追问（或当 ready 时收束）。

${JSON_ONLY}
格式：
{
  "questions":[
    {"text":"问题","reason":"为什么问这个","options":["选项1","选项2"]}
  ],
  "summary":"我目前的理解是…（一两句话）",
  "ready":false
}`,
  };
}

