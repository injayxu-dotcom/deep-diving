/**
 * 维度专属规则（2026-10-17 重构）。
 *
 * 为什么必须分维度写：改造前六个维度共用同一段要求 ——「4-12 字、具象、别套路」。
 * 这套标准对「视觉联想」够用，对「文化隐喻」几乎等于没要求：模型只要交出
 * 「有文化味道的画面」（渔民打捞珍珠、灯火）就算"具象"，而它要的其实是
 * 「有出处的典故」（画龙点睛、庖丁解牛）。同一个 prompt 模板套六个维度，
 * 输出的必然是六个维度的平均值，也就是最平庸的那一档。
 *
 * 所以每一维都写三样东西：
 *   gate —— 一条可判定的硬门槛（"不合格"能当场指出来，不是形容词）
 *   bad  —— 该维度最容易被误当成合格品的输出（实测/预判的高频错误）
 *   good —— 合格的样子，且示范了「怎么把推导写出来」
 *
 * 六维提示词应让每个方向产生不同的思考动作，而非共用「自由联想」再换标题。
 * 结果需要同时满足维度特征、与种子的推导关系、可视化程度和批次差异。
 */
interface DimRule {
  /** 该维度独有的思考动作 */
  method: string;
  gate: string;
  /** 同批结果的覆盖要求，避免六条答案挤在同一种表达里 */
  coverage: string;
  bad: string[];
  good: string[];
  extra?: string;
  /** why 字段里必须交代的那件事 —— 每维不同，这是"能不能被检验"的关键 */
  whyHint: string;
  /**
   * 额外的独立判据板块（目前只有谐音维度用）。
   * 单独成节而不是塞进 gate：gate 讲"必须成立什么"，这里讲"怎么判定成立"，
   * 混在一起模型会把判定标准当成又一条硬门槛，写得更死却没学会怎么判断。
   */
  phonetics?: string;
  /**
   * 覆盖输出格式里对 word 的定义。
   * 谐音维度的 word 是「一句能用的文案」，不是「一个画面」，而格式那行是全局共用的 ——
   * 不改的话它会把模型往"描述画面"拉回去，白改一整段维度说明。
   */
  wordDesc?: string;
  /** 覆盖筛选第 3 条：默认要求"画面成立"，谐音维度要的是"文案落地" */
  frame?: string;
}

